func ServerAdd(h string, o ServerAddOptions) (ServerAddResult, error) {
	c, e := loadConfig(h)
	if e != nil {
		return ServerAddResult{}, e
	}
	return serverAddConfig(h, c, o)
}
func serverAddConfig(h string, c *config.Config, o ServerAddOptions) (ServerAddResult, error) {
	return serverAddConfigWithSave(h, c, o, config.Save)
}
func serverAddConfigWithSave(h string, c *config.Config, o ServerAddOptions, save func(string, *config.Config) error) (ServerAddResult, error) {
	original := append([]config.Server(nil), c.Servers...)
	fail := func(e error) (ServerAddResult, error) { c.Servers = original; return ServerAddResult{}, e }
	if _, ok := servers.Lookup(o.Protocol); !ok {
		return fail(serverValidationError(&cli.Error{Code: "CONFIG_INVALID", Message: "servers[0].protocol is not registered", Exit: cli.ExitUsage}))
	}
	if o.Name != "" && !serverNameValid(o.Name) {
		return fail(serverValidationError(&cli.Error{Code: "CONFIG_INVALID", Message: "servers[0].name must be 1 to 32 letters, digits, dots, underscores or hyphens", Exit: cli.ExitUsage}))
	}
	if o.Accounts == "" {
		o.Accounts = "*"
	}
	n := o.Name
	if n == "" {
		n = o.Protocol + "-" + strconv.Itoa(o.Port)
		if o.Protocol == "shadowsocks" {
			n = "ss-" + strconv.Itoa(o.Port)
		}
	}
	if o.Accounts != "*" {
		for _, a := range strings.Split(o.Accounts, ",") {
			if !config.ValidAccountLogin(a) {
				return fail(serverValidationError(&cli.Error{Code: "CONFIG_INVALID", Message: "servers[0].accounts contains an invalid account login", Exit: cli.ExitUsage}))
			}
		}
	}
	if _, i := c.GetServer(n); i >= 0 {
		return fail(serverConflict("server name is already configured"))
	}
	b := o.Bind
	if b == "" {
		b = "0.0.0.0"
	}
	entry := config.Server{Name: n, Protocol: o.Protocol, Bind: b, Port: o.Port, Accounts: o.Accounts, Params: cloneParams(o.Params), PublicHost: o.PublicHost, Default: o.Default}
	if e := checkPortConflict(c, entry); e != nil {
		return fail(e)
	}
	c.Servers = append(c.Servers, entry)
	if e := c.Validate(); e != nil {
		return fail(serverValidationError(e))
	}
	specs, e := c.ResolveServers()
	if e != nil {
		return fail(serverValidationError(e))
	}
	var target servers.Spec
	for _, sp := range specs {
		if sp.Name == n {
			target = sp
		}
	}
	st := servers.NewStore(h)
	peers := []servers.Spec{}
	for _, sp := range specs {
		if sp.Name == n || sp.Port != entry.Port || !serverSameBind(sp.Bind, entry.Bind) {
			continue
		}
		p, _ := servers.Lookup(sp.Protocol)
		np, _ := servers.Lookup(entry.Protocol)
		if servers.IsUDPBound(p) != servers.IsUDPBound(np) {
			continue
		}
		ap, er := st.Apply(sp)
		if er != nil {
			return fail(serverError("INTERNAL", "server secrets could not be loaded", cli.ExitInternal))
		}
		peers = append(peers, ap)
	}
	_, receipt, e := st.EnsureSecretsValidated(target, peers)
	if e != nil {
		var ce *cli.Error
		if errors.As(e, &ce) {
			return fail(ce)
		}
		return fail(serverError("INTERNAL", "server secrets could not be stored", cli.ExitInternal))
	}
	if e = save(config.ConfigPath(h), c); e != nil {
		cleanup := st.CleanupCreated(receipt)
		ce := serverError("INTERNAL", "server configuration could not be saved", cli.ExitInternal)
		if cleanup != nil {
			ce.(*cli.Error).Hint = "server-secrets.ktav may contain leftover secrets for server " + n
		}
		return fail(&serverSaveError{cliErr: ce.(*cli.Error), cause: e})
	}
	keys := []string{}
	for _, f := range receipt.Material {
		keys = append(keys, f.Key)
	}
	for login, fs := range receipt.Users {
		for _, f := range fs {
			keys = append(keys, login+"."+f.Key)
		}
	}
	sort.Strings(keys)
	return ServerAddResult{serverView: serverPublic(c, entry), GeneratedKeys: keys}, nil
}
func cloneParams(m map[string]string) map[string]string {
	n := map[string]string{}
	for k, v := range m {
		n[k] = v
	}
	return n
}
func checkPortConflict(c *config.Config, e config.Server) error {
	p, _ := servers.Lookup(e.Protocol)
	udp := servers.IsUDPBound(p)
	if !udp && c.Listen.Port == e.Port && serverBindsOverlap(c.Listen.Bind, e.Bind) {
		return serverPortConflict("server port conflicts with the proxy listener")
	}
	tls, tr := servers.ShareMode(servers.Spec{Protocol: e.Protocol, Params: e.Params})
	for _, s := range c.Servers {
		sp, ok := servers.Lookup(s.Protocol)
		if ok && servers.IsUDPBound(sp) != udp {
			continue
		}
		if s.Port != e.Port || !serverBindsOverlap(s.Bind, e.Bind) {
			continue
		}
		st, sr := servers.ShareMode(servers.Spec{Protocol: s.Protocol, Params: s.Params})
		if !udp && serverSameBind(s.Bind, e.Bind) && (st || sr) && (tls || tr) {
			continue
		}
		return serverPortConflict("server port conflicts with an existing listener")
	}
	return nil
}
func ServerUpdate(h, n string, o ServerUpdateOptions) (serverView, error) {
	c, e := loadConfig(h)
	if e != nil {
		return serverView{}, e
	}
	return serverUpdateConfig(h, c, n, o)
}
func serverUpdateConfig(h string, c *config.Config, n string, o ServerUpdateOptions) (serverView, error) {
	return serverUpdateConfigWithSave(h, c, n, o, config.Save)
}
func serverUpdateConfigWithSave(h string, c *config.Config, n string, o ServerUpdateOptions, save func(string, *config.Config) error) (serverView, error) {
	s, i := c.GetServer(n)
	if s == nil {
		return serverView{}, serverNotFound()
	}
	old := *s
	s.Params = cloneParams(s.Params)
	if o.PublicHost != nil {
		s.PublicHost = *o.PublicHost
	}
	if o.Bind != nil {
		s.Bind = *o.Bind
	}
	if o.Port != nil {
		s.Port = *o.Port
	}
	if o.Accounts != nil {
		s.Accounts = *o.Accounts
	}
	for k, v := range o.Params {
		if s.Params == nil {
			s.Params = map[string]string{}
		}
		s.Params[k] = v
	}
	if e := checkPortExcept(c, i); e != nil {
		c.Servers[i] = old
		return serverView{}, e
	}
	if e := c.Validate(); e != nil {
		c.Servers[i] = old
		return serverView{}, serverValidationError(e)
	}
	specs, e := c.ResolveServers()
	if e != nil {
		c.Servers[i] = old
		return serverView{}, serverValidationError(e)
	}
	st := servers.NewStore(h)
	var target servers.Spec
	for _, sp := range specs {
		if sp.Name == n {
			target = sp
			break
		}
	}
	peers := []servers.Spec{}
	for _, sp := range specs {
		if sp.Name == n || sp.Port != target.Port || !serverSameBind(sp.Bind, target.Bind) {
			continue
		}
		p, _ := servers.Lookup(sp.Protocol)
		tp, _ := servers.Lookup(target.Protocol)
		if servers.IsUDPBound(p) != servers.IsUDPBound(tp) {
			continue
		}
		ap, er := st.Apply(sp)
		if er != nil {
			c.Servers[i] = old
			return serverView{}, serverError("INTERNAL", "server secrets could not be loaded", cli.ExitInternal)
		}
		peers = append(peers, ap)
	}
	_, receipt, e := st.EnsureSecretsValidated(target, peers)
	if e != nil {
		c.Servers[i] = old
		var ce *cli.Error
		if errors.As(e, &ce) {
			return serverView{}, ce
		}
		return serverView{}, serverError("INTERNAL", "server secrets could not be stored", cli.ExitInternal)
	}
	if e = save(config.ConfigPath(h), c); e != nil {
		cleanup := st.CleanupCreated(receipt)
		c.Servers[i] = old
		ce := serverError("INTERNAL", "server configuration could not be saved", cli.ExitInternal)
		if cleanup != nil {
			ce.(*cli.Error).Hint = "server-secrets.ktav may contain leftover secrets for server " + n
		}
		return serverView{}, &serverSaveError{cliErr: ce.(*cli.Error), cause: e}
	}
	return serverPublic(c, c.Servers[i]), nil
}
func checkPortExcept(c *config.Config, i int) error {
	e := c.Servers[i]
	p, _ := servers.Lookup(e.Protocol)
	udp := servers.IsUDPBound(p)
	if !udp && c.Listen.Port == e.Port && serverBindsOverlap(c.Listen.Bind, e.Bind) {
		return serverPortConflict("server port conflicts with the proxy listener")
	}
	tls, tr := servers.ShareMode(servers.Spec{Protocol: e.Protocol, Params: e.Params})
	for j, s := range c.Servers {
		if j == i {
			continue
		}
		sp, ok := servers.Lookup(s.Protocol)
		if ok && servers.IsUDPBound(sp) != udp {
			continue
		}
		if s.Port != e.Port || !serverBindsOverlap(s.Bind, e.Bind) {
			continue
		}
		st, sr := servers.ShareMode(servers.Spec{Protocol: s.Protocol, Params: s.Params})
		if !udp && serverSameBind(s.Bind, e.Bind) && (st || sr) && (tls || tr) {
			continue
		}
		return serverPortConflict("server port conflicts with an existing listener")
	}
	return nil
}
func ServerRemove(h, n string) (ServerRemoveResult, error) {
	c, e := loadConfig(h)
	if e != nil {
		return ServerRemoveResult{}, e
	}
	return removeConfig(h, c, n)
}
func removeConfig(h string, c *config.Config, n string) (ServerRemoveResult, error) {
	s, i := c.GetServer(n)
	if i < 0 {
		return ServerRemoveResult{}, serverNotFound()
	}
	accounts := []string{}
	if s.Accounts == "*" {
		resolved, resolveErr := c.ResolveServers()
		if resolveErr != nil {
			return ServerRemoveResult{}, serverValidationError(resolveErr)
		}
		for _, spec := range resolved {
			if spec.Name == n {
				accounts = append(accounts, spec.Accounts...)
				break
			}
		}
	} else {
		accounts = strings.Split(s.Accounts, ",")
	}
	old := c.Servers[i]
	c.Servers = append(c.Servers[:i], c.Servers[i+1:]...)
	if e := config.Save(config.ConfigPath(h), c); e != nil {
		c.Servers = append(c.Servers[:i], append([]config.Server{old}, c.Servers[i:]...)...)
		return ServerRemoveResult{}, serverError("INTERNAL", "server configuration could not be saved", cli.ExitInternal)
	}
	if e := servers.NewStore(h).Remove(n); e != nil {
		c.Servers = append(c.Servers[:i], append([]config.Server{old}, c.Servers[i:]...)...)
		restoreErr := config.Save(config.ConfigPath(h), c)
		ce := serverError("INTERNAL", "server secrets could not be removed", cli.ExitInternal)
		if restoreErr != nil {
			ce.(*cli.Error).Hint = "server configuration rollback failed; inspect config.ktav for server " + n
		}
		return ServerRemoveResult{}, ce
	}
	return ServerRemoveResult{Name: n, Accounts: accounts}, nil
}
func ServerRotate(h, n, a string) (ServerRotateResult, error) {
	c, e := loadConfig(h)
	if e != nil {
		return ServerRotateResult{}, e
	}
	return rotateConfig(h, c, n, a)
}
func rotateConfig(h string, c *config.Config, n, a string) (ServerRotateResult, error) {
	_, i := c.GetServer(n)
	if i < 0 {
		return ServerRotateResult{}, serverNotFound()
	}
	ss, e := c.ResolveServers()
	if e != nil {
		return ServerRotateResult{}, serverValidationError(e)
	}
	for _, s := range ss {
		if s.Name == n {
			if a != "" && !serverHasAccount(s.Accounts, a) {
				return ServerRotateResult{}, cli.Usage("account is not served by this server")
			}
			if _, e = servers.NewStore(h).Rotate(s, a); e != nil {
				return ServerRotateResult{}, serverError("INTERNAL", "server secret rotation failed", cli.ExitInternal)
			}
			accounts := []string{}
			if p, _ := servers.Lookup(s.Protocol); p != nil && p.SingleUser() {
				return ServerRotateResult{Name: n, SharedCredentials: true}, nil
			}
			if a != "" {
				accounts = []string{a}
			} else {
				accounts = append(accounts, s.Accounts...)
			}
			return ServerRotateResult{Name: n, Accounts: accounts}, nil
		}
	}
	return ServerRotateResult{}, serverNotFound()
}

// ServerLink returns a connection link containing credentials; callers must treat it as secret.
func ServerLink(h, n string, o ServerLinkOptions) (string, error) {
	c, e := loadConfig(h)
	if e != nil {
		return "", e
	}
	v, _, e := linkConfig(h, c, n, o)
	return v, e
}
func linkConfig(h string, c *config.Config, n string, o ServerLinkOptions) (string, string, error) {
	entry, _ := c.GetServer(n)
	if entry == nil {
		return "", "", serverNotFound()
	}
	ss, e := c.ResolveServers()
	if e != nil {
		return "", "", serverValidationError(e)
	}
	var spec servers.Spec
	for _, s := range ss {
		if s.Name == n {
			spec = s
		}
	}
	st := servers.NewStore(h)
	if e = st.Load(); e != nil {
		return "", "", serverError("INTERNAL", "server secrets could not be loaded", cli.ExitInternal)
	}
	spec, e = st.Apply(spec)
	if e != nil {
		return "", "", serverError("INTERNAL", "server secrets could not be loaded", cli.ExitInternal)
	}
	login := o.Account
	if login == "" {
		if len(spec.Accounts) != 1 {
			return "", "", cli.Usage("server link requires --account when the server has multiple accounts")
		}
		login = spec.Accounts[0]
	}
	if !serverHasAccount(spec.Accounts, login) {
		return "", "", cli.Usage("account is not served by this server")
	}
	host := o.Host
	if host == "" {
		host = entry.PublicHost
	}
	host = strings.Trim(host, "[]")
	if host == "" || !validServerHost(host) {
		return "", "", cli.Usage("server link requires a hostname or IP without a port")
	}
	p, _ := servers.Lookup(spec.Protocol)
	if o.Format == "" {
		o.Format = "uri"
	}
	if o.Format != "uri" && o.Format != "mihomo" {
		return "", "", cli.Usage("server link: invalid arguments")
	}
	var link string
	if o.Format == "mihomo" {
		m, ok := p.(servers.MihomoLinker)
		if !ok {
			return "", "", cli.Usage("protocol does not support mihomo format")
		}
		link, e = m.Mihomo(spec, login, host)
	} else {
		link, e = p.Link(spec, login, host)
	}
	if e != nil {
		return "", "", serverValidationError(e)
	}
	return link, login, nil
}
func serverSameBind(a, b string) bool {
	if a == "" {
		a = "0.0.0.0"
	}
	if b == "" {
		b = "0.0.0.0"
	}
	ia, ib := net.ParseIP(a), net.ParseIP(b)
	if ia == nil || ib == nil {
		return a == b
	}
	return ia.Equal(ib)
}
func serverBindsOverlap(a, b string) bool {
	if a == "" {
		a = "0.0.0.0"
	}
	if b == "" {
		b = "0.0.0.0"
	}
	ia, ib := net.ParseIP(a), net.ParseIP(b)
	return ia != nil && ib != nil && (ia.Equal(ib) || ia.IsUnspecified() && (ia.To4() == nil || ib.To4() != nil) || ib.IsUnspecified() && (ib.To4() == nil || ia.To4() != nil))
}
func validServerHost(h string) bool {
	if h == "" || strings.ContainsAny(h, " /\t\r\n?#@") || strings.Contains(h, "[") || strings.Contains(h, "]") {
		return false
	}
	if net.ParseIP(h) != nil {
		return true
	}
	u, e := url.Parse("//" + h)
	return e == nil && u.Host == h && u.Hostname() != "" && u.Port() == "" && (u.Hostname() == "localhost" || strings.Contains(u.Hostname(), "."))
}
