type ServerProtocol struct {
	PublicHost                          ServerParameter
	Name, Label, Description, Transport string
	SingleUser                          bool
	Parameters                          []ServerParameter
}
type ServerParameter struct {
	Name, Label, Description, Default, Kind string
	Required, Secret, AutoGenerated         bool
	Min, Max                                int
	Choices                                 []string
}

func ServerProtocols() []ServerProtocol {
	out := []ServerProtocol{}
	for _, p := range servers.Registered() {
		m, _ := servers.Metadata(p.Name())
		tr := "TCP"
		if servers.IsUDPBound(p) {
			tr = "UDP (QUIC)"
		}
		ps := []ServerParameter{}
		for _, q := range m.Parameters {
			ps = append(ps, ServerParameter{Name: q.Name, Label: q.Label, Description: q.Description, Default: q.Default, Kind: q.Kind, Required: q.Required, Secret: q.Secret, AutoGenerated: q.AutoGenerated, Min: q.Min, Max: q.Max, Choices: append([]string(nil), q.Choices...)})
		}
		out = append(out, ServerProtocol{PublicHost: ServerParameter{Name: m.PublicHost.Name, Label: m.PublicHost.Label, Description: m.PublicHost.Description, Default: m.PublicHost.Default, Kind: m.PublicHost.Kind, Required: m.PublicHost.Required, Secret: m.PublicHost.Secret, AutoGenerated: m.PublicHost.AutoGenerated, Min: m.PublicHost.Min, Max: m.PublicHost.Max, Choices: append([]string(nil), m.PublicHost.Choices...)}, Name: p.Name(), Label: m.Label, Description: m.Description, Transport: tr, SingleUser: p.SingleUser(), Parameters: ps})
	}
	return out
}

