type serverSaveError struct {
	cliErr *cli.Error
	cause  error
}

func (e *serverSaveError) Error() string { return e.cliErr.Error() }
func (e *serverSaveError) Unwrap() error { return e.cause }
func (e *serverSaveError) As(target any) bool {
	p, ok := target.(**cli.Error)
	if ok {
		*p = e.cliErr
	}
	return ok
}

