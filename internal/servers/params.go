package servers

// Parameter describes a supported, non-secret configuration option.
type Parameter struct {
	Name, Label, Description, Default, Kind string
	Required, Secret, AutoGenerated         bool
	Min, Max                                int
	Choices                                 []string
}

type ProtocolMetadata struct {
	Label, Description string
	PublicHost         Parameter
	Parameters         []Parameter
}

// Metadata returns the exhaustive wizard schema keyed by registered protocol name.
func Metadata(name string) (ProtocolMetadata, bool) {
	m, ok := parameterMetadata[name]
	if !ok {
		return ProtocolMetadata{}, false
	}
	return cloneMetadata(m), true
}

func cloneMetadata(m ProtocolMetadata) ProtocolMetadata {
	m.Parameters = append([]Parameter(nil), m.Parameters...)
	for i := range m.Parameters {
		m.Parameters[i].Choices = append([]string(nil), m.Parameters[i].Choices...)
	}
	m.PublicHost.Choices = append([]string(nil), m.PublicHost.Choices...)
	return m
}

func parameter(name, label, description, kind string) Parameter {
	return Parameter{Name: name, Label: label, Description: description, Kind: kind}
}

